def nome_zona(h3_index: str) -> str:
    if h3_index in ZONAS_PORTO:
        return ZONAS_PORTO[h3_index]
    try:
        import h3 as h3lib
        lat, lng = h3lib.cell_to_latlng(h3_index)
        # Tenta obter nome via Nominatim (OpenStreetMap, gratuito)
        import requests
        resp = requests.get(
            "https://nominatim.openstreetmap.org/reverse",
            params={"lat": lat, "lon": lng, "format": "json", "zoom": 14},
            headers={"User-Agent": "bolt-alertas-tvde/1.0"},
            timeout=5
        )
        if resp.status_code == 200:
            dados = resp.json()
            addr = dados.get("address", {})
            nome = (addr.get("suburb") or addr.get("quarter") or
                    addr.get("neighbourhood") or addr.get("city_district") or
                    addr.get("town") or addr.get("village") or
                    addr.get("municipality") or f"({lat:.4f}, {lng:.4f})")
            cidade = addr.get("city") or addr.get("town") or ""
            if cidade and cidade.lower() not in nome.lower():
                return f"{nome} / {cidade}"
            return nome
    except Exception:
        pass
    return f"Zona Porto ({lat:.4f}, {lng:.4f})"
